#!/usr/bin/env node
'use strict';
/**
 * Generate docs/reference/CARDS.md from src/data/cards.js, so the written
 * catalog can never drift from the game.
 *
 *   node tools/catalog.js            write the file
 *   node tools/catalog.js --check    exit 1 if the file on disk is stale
 */
const fs = require('fs');
const path = require('path');
const T = require('./load')();

const EL = { M: 'Mass', C: 'Charge', S: 'Space', T: 'Time' };
const out = [];
out.push('# Card catalog — 99 traits, two faces each');
out.push('');
out.push('> Generated by `npm run catalog` from `src/data/cards.js`. Do not edit by hand.');
out.push('');
out.push(
  'Every trait is a card with two faces. The **Physical** face costs AP, has a short cooldown and scales with **P** ' +
    '(`base + P`). The **Ethereal** face costs AP plus an etherion of the card’s colour, has a longer cooldown, and does ' +
    'what the physical face cannot — a *capability* that scales with **E** (P may also scale a mundane sub-part). ' +
    'Playing either face sends the whole card to the track for that face’s cooldown (+ duration).',
);
out.push('');
out.push(
  'The design intends an Ethereal capability to exist only at E ≥ 1. v2.0 does not enforce that: an Ethereal face can be ' +
    'played at E 0, with its E-0 numbers (see the known issues in `docs/HANDOFF.md`).',
);
out.push('');
out.push(
  'Each line shows the face at **P0 / E1** and, in italics, at **P3 / E3**. ★ = signature trait, ☆ = minor signature. ' +
    'Caps: P 3, E 3. A hero starts with 6 cards and may grow to 9 — never more than 3 of 9 from one bloodline.',
);
out.push('');

T.SPECIES_ORDER.forEach((sp, i) => {
  const S = T.SPECIES[sp];
  out.push(`## ${i} · ${S.name} — leans ${S.lean}`);
  out.push('');
  out.push(`*${S.tagline}*`);
  out.push('');
  for (const c of T.cardsOf(sp)) {
    const sig = c.sig >= 2 ? ' ★' : c.sig === 1 ? ' ☆' : '';
    const P = c.P;
    const E = c.E;
    const elt = E.elt || c.el;
    const pCost = `${P.ap} AP · CD ${P.cd}${P.dur ? ' · Dur ' + P.dur : ''}`;
    const eCost = `${E.ap} AP + ${E.el} ${EL[elt]} · CD ${E.cd}${E.dur ? ' · Dur ' + E.dur : ''}`;
    const p0 = P.txt(0, 0);
    const p3 = P.txt(3, 0);
    const e1 = E.txt(0, 1);
    const e3 = E.txt(3, 3);
    out.push(`**${c.name}**${sig} · ${EL[c.el]} · \`${c.id}\``);
    out.push('');
    out.push(`- *Phys — ${P.n}* · ${pCost} — ${p0}${p3 !== p0 ? ` *(P3: ${p3})*` : ''}`);
    out.push(`- *Eth — ${E.n}* · ${eCost} — ${e1}${e3 !== e1 ? ` *(P3/E3: ${e3})*` : ''}`);
    out.push('');
  }
});

const file = path.join(__dirname, '..', 'docs', 'reference', 'CARDS.md');
const text = out.join('\n');
if (process.argv.includes('--check')) {
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error('docs/reference/CARDS.md is stale — run `npm run catalog`.');
    process.exit(1);
  }
  console.log('docs/reference/CARDS.md is up to date.');
} else {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`wrote docs/reference/CARDS.md — ${T.CARDS.length} cards`);
}
