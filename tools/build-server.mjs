/**
 * The engine for the server: the same files the game loads (src/manifest.json, "engine"), concatenated into
 * one ES module the Cloudflare Worker imports, so a pilot or a canon note shared online is checked by the
 * game's own rules (T.validMade, T.canonRecord) and not by a second copy of them.
 *
 *   node tools/build-server.mjs      → server/src/engine.gen.js (generated; not committed)
 *
 * wrangler.toml runs this before every `wrangler dev` and `wrangler deploy`.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const outPath = join(root, 'server', 'src', 'engine.gen.js');

/** The module's text. The engine files attach to `global.T` when there is no window, as in Node. */
export function engineModule() {
  const manifest = JSON.parse(readFileSync(join(root, 'src', 'manifest.json'), 'utf8'));
  const body = manifest.engine
    .map((rel) => `\n/* ───── ${rel} ───── */\n` + readFileSync(join(root, 'src', rel), 'utf8'))
    .join('\n');
  return (
    '// GENERATED by tools/build-server.mjs from src/manifest.json "engine". Do not edit.\n' +
    'const global = { T: {} };\n' +
    'const window = undefined;\n' +
    body +
    '\nexport const T = global.T;\nexport default T;\n'
  );
}

const isMain =
  !!process.argv[1] && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase();
if (isMain) {
  const text = engineModule();
  // written only when it changed, so `wrangler dev`, which watches it, does not rebuild in a loop
  const same = existsSync(outPath) && readFileSync(outPath, 'utf8') === text;
  if (!same) writeFileSync(outPath, text);
  console.log(`${same ? 'unchanged' : 'built'} server/src/engine.gen.js — ${(text.length / 1024).toFixed(0)} KB`);
}
